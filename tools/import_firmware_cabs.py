"""Rebuild the offline firmware lookup from paired CAB producer and verification receipts."""
import argparse
import json
import re
from pathlib import Path

NAMES = {'fsbl': 'FSBL', 'bootinfo': 'BootInfo', 'opensbi': 'OpenSBI', 'edk2': 'EDK2',
         'ec': 'EC', 'esos': 'ESOS'}


def collect(inputs, verification, rows):
    chip = verification['board']
    if chip not in ('k1', 'k3') or verification['scope'] != 'independent_firmware_cab_verification':
        raise ValueError('unknown CAB verification record')
    if inputs.get('scope') == 'csce2010_ec_firmware_release' and chip == 'k3':
        components = {'ec': dict(inputs['image'], guid=inputs['guid'], version=inputs['version'])}
    elif chip == 'k1' and inputs.get('scope') == 'k1_muse_pi_pro_self_reported_component_set':
        components = dict(inputs['components'])
        components['fsbl'] = components.pop('spl_fsbl')
    elif chip == 'k3' and inputs.get('scope') == 'k3_unified_component_cabinets':
        components = {item['name']: item for item in inputs['components']}
    else:
        raise ValueError('CAB inputs do not match the verified board family')
    for name, item in components.items():
        if name not in NAMES:
            continue
        version = item.get('version', item.get('release_version'))
        digest = item.get('sha256', item.get('fit_sha256', ''))
        if not re.fullmatch('[0-9a-f]{64}', digest) or type(version) is not int or not 0 < version <= 0xffffffff:
            raise ValueError('invalid producer receipt')
        key = chip, NAMES[name], digest
        previous, cabinets = rows.setdefault(key, (version, set()))
        if previous != version:
            raise ValueError('conflicting versions for the same payload')
        verified = verification['components'].get(name)
        if verified is None:
            continue
        cab = verified['files'][name + '.cab']
        if (not all(verified.get(flag) is True for flag in ('cab_signature', 'capsule_signature', 'fwupd_parsed'))
                or verified['version'] != version or item.get('guid', verified['guid']) != verified['guid']
                or not re.fullmatch('[0-9a-f]{64}', cab)):
            raise ValueError('CAB verification does not match producer receipt')
        cabinets.add(cab)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pair', nargs=2, required=True, action='append', metavar=('INPUTS', 'VERIFICATION'),
                        help='two receipts from the same build')
    args = parser.parse_args()
    rows = {}
    for inputs, verification in args.pair:
        collect(json.loads(Path(inputs).read_bytes()), json.loads(Path(verification).read_bytes()), rows)
    print('"""Firmware payload versions and verified CAB SHA-256 values. Generated by import_firmware_cabs.py."""')
    print('CAB_COMPONENTS = {')
    for key, (version, cabinets) in sorted(rows.items()):
        print(f'    {key!r}: ({version}, {tuple(sorted(cabinets))!r}),')
    print('}')


if __name__ == '__main__':
    main()
