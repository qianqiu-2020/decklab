// Owns one terminal view: lifetime, IO, geometry, redraw and ordered input.
// Device selection, archive navigation and session catalogs are injected.
(function (global) {
  'use strict';
  function create(options) {
    var $ = options.byId, fetch = options.fetch;
    var view = null, term = null, loopGen = 0;
    var DEFAULT_TERMINAL_FONT_SIZE = 14.5;
    function isCurrent(ctx) {
      return !!ctx && view === ctx && ctx.gen === loopGen;
    }

    function disposeView() {
      var old = view;
      view = null; term = null; loopGen++;
      if (!old) return;
      if (old.scrollHandler && $('d-term').removeEventListener) {
        $('d-term').removeEventListener('click', old.scrollHandler, true);
      }
      if (old.wheelHandler && $('d-term').removeEventListener) {
        $('d-term').removeEventListener('wheel', old.wheelHandler, false);
      }
      if (old.ctrl) old.ctrl.abort();
      if (old.stream) old.stream.close();
      clearTimeout(old.loopTimer);
      clearTimeout(old.inputTimer);
      clearTimeout(old.sizeTimer);
      clearTimeout(old.serialSizeTimer);
      clearTimeout(old.selTimer);
      clearTimeout(old.navTimer);
      options.clearCommandDecorations(old);
      if (old.refreshFrame && window.cancelAnimationFrame) window.cancelAnimationFrame(old.refreshFrame);
      // reset() 不会清空 xterm 的异步解析队列；旧 CSI 6n 还可能触发 onData，
      // 把上一台的终端应答写到新设备。销毁实例，并让所有旧回调检查所属视图。
      old.term.dispose();
    }

    /* ---------- 终端模拟器 ---------- */
    function createView(key, sid) {
      disposeView();
      options.onSelect(key, sid);
      $('b-rescue').disabled = false;
      var board = options.board(key) || {};
      var selectedSession = options.session(sid) || {};
      var isAgentSession = selectedSession.kind === 'ssh' && !!selectedSession.actor
        && selectedSession.actor !== 'web' && !options.takenOver(sid);
      var ctx = { key: key, serial: board.serial, connectionId: board.connection_id,
                  byPath: board.by_path || board.last_path,
                  readonly: selectedSession.kind === 'log' || isAgentSession
                    || (sid === 'serial' && !!board.input_owner && !options.ownsInput(board.input_owner)),
                  inputOwner: board.input_owner || null,
                  canTakeover: isAgentSession, kind: selectedSession.kind || 'serial',
                  sid: sid, gen: loopGen, off: 0, readSeq: 0, sessionsSeq: 0, activitySeq: 0,
                  logsSeq: 0,
                  inputQueue: [], inputSending: false, inputTimer: 0,
                  navEntries: [], navSelected: -1, navTimer: 0, navRendered: false,
                  commandDecorations: [], commandColorSignature: '',
                  lastSel: '', searchQuery: '', searchMatch: -1,
                  renderQueue: [], renderBusy: false, renderEpoch: 0, geometryGen: 0, serialRows: 24, serialMode: 'text', bootScanTail: '', phaseScanTail: '', linuxConsole: false };
      view = ctx;
      resetProgress(ctx);
      options.setInputMode(ctx);
      $('b-serial-size').hidden = sid !== 'serial';
      term = ctx.term = new Terminal({
        // 归档文件常用单独 LF；xterm 的 LF 默认不回到第 1 列，会呈现阶梯状。
        // 实时串口/pty 保留原始 CR/LF，避免改变全屏终端协议。
        convertEol: ctx.kind === 'log',
        scrollback: 8000,
        cursorBlink: !ctx.readonly,
        allowProposedApi: true,
        windowOptions: {setWinSizeChars: sid === 'serial'},
        fontFamily: 'ui-monospace, "Cascadia Mono", Consolas, "Liberation Mono", Menlo, monospace',
        fontSize: DEFAULT_TERMINAL_FONT_SIZE,
        theme: { background: '#0F151D', foreground: '#DCE5F0', cursor: '#82C5FF',
                 selectionBackground: '#E6B45D', selectionForeground: '#0F151D' }
      });
      ctx.fit = new FitAddon.FitAddon();
      ctx.term.loadAddon(ctx.fit);
      $('d-term').textContent = '';
      $('d-command-nav').textContent = '';
      $('command-nav-count').textContent = '0 条';
      ctx.term.open($('d-term'));
      if (sid === 'serial') {
        ctx.term.parser.registerCsiHandler({final: 't'}, function (params) {
          if (!isCurrent(ctx) || params[0] !== 8 || params.length !== 3) return false;
          if (ctx.screenManaged) { applyManagedGeometry(ctx, {rows: params[1], cols: params[2]}); return true; }
          applySerialGeometry(ctx, {rows: params[1], cols: params[2]});
          return true;
        });
        ctx.term.parser.registerCsiHandler({prefix: '>', final: 'z'}, function (params) {
          // Generated by the APT decoder, never written to the board or archives.
          // Apply the source geometry only when this point in the stream parses.
          if (!isCurrent(ctx)) return true;
          if (ctx.screenManaged) { applyManagedGeometry(ctx, {rows: params[0], cols: ctx.screenGeometry.cols}); return true; }
          applySerialGeometry(ctx, {rows: params[0], cols: ctx.serialCols || 80});
          return true;
        });
      }
      // Some Chromium/Linux themes expose an overlay scrollbar whose track
      // accepts wheel input but ignores a track click.  Keep native dragging,
      // and provide the expected page jump when the click lands on xterm's
      // viewport edge.
      ctx.scrollHandler = function (event) {
        if (!isCurrent(ctx) || !event || !event.target || !event.target.classList
            || !event.target.classList.contains('xterm-viewport')) return;
        var viewport = event.target;
        var rect = viewport.getBoundingClientRect && viewport.getBoundingClientRect();
        if (!rect || event.clientX < rect.right - 24 || !viewport.scrollHeight) return;
        var ratio = Math.max(0, Math.min(1, (event.clientY - rect.top) / rect.height));
        viewport.scrollTop = Math.max(0, ratio * viewport.scrollHeight - viewport.clientHeight / 2);
      };
      $('d-term').addEventListener('click', ctx.scrollHandler, true);
      // xterm consumes wheel input, but at the first/last line some browsers
      // chain the unused delta to the page.  Stop that chain while preserving
      // xterm's own target listener and scrollbar behavior.
      ctx.wheelHandler = function (event) {
        if (!isCurrent(ctx) || !event) return;
        var viewport = ctx.term.element && ctx.term.element.querySelector
          ? ctx.term.element.querySelector('.xterm-viewport') : null;
        if (!viewport) return;
        var atTop = viewport.scrollTop <= 0;
        var atBottom = viewport.scrollTop + viewport.clientHeight >= viewport.scrollHeight - 1;
        if ((event.deltaY < 0 && atTop) || (event.deltaY > 0 && atBottom)) {
          if (event.preventDefault) event.preventDefault();
        }
        if (event.stopPropagation) event.stopPropagation();
      };
      $('d-term').addEventListener('wheel', ctx.wheelHandler, { passive: false });
      SerialdTerminalPolicy.install(ctx, {
        isCurrent: isCurrent,
        keyboardEnabled: function () { return $('d-kbd').checked; },
        send: send,
        copyText: options.copyText,
        copySelection: options.copySel
      });
      return ctx;
    }

    function resetProgress(ctx) {
      if (ctx.sid !== 'serial' || !window.SerialdSerialProgress) return;
      ctx.progress = window.SerialdSerialProgress.create({
        canonical: true, rows: function () { return ctx.term.rows; },
        sourceRows: function () { return ctx.serialCols ? ctx.serialRows : 0; }
      });
    }

    function redrawTerminal() {
      var ctx = view;
      if (!isCurrent(ctx)) return;
      ctx.readSeq++;
      if (ctx.ctrl) ctx.ctrl.abort();
      if (ctx.stream) { ctx.stream.close(); ctx.stream = null; }
      clearTimeout(ctx.loopTimer);
      if (ctx.refreshFrame && window.cancelAnimationFrame) {
        window.cancelAnimationFrame(ctx.refreshFrame); ctx.refreshFrame = 0;
      }
      options.clearTerminalSearch(false);
      options.clearCommandDecorations(ctx);
      try { ctx.term.reset(); ctx.term.clear(); } catch (e) {}
      ctx.navRendered = false;
      options.renderCommandNav(ctx);
      ctx.off = 0; ctx.initialRendered = false; ctx.geometryGen++;
      ctx.renderEpoch++; ctx.renderQueue = []; ctx.renderBusy = true; ctx.lastRenderedOff = null;
      var epoch = ctx.renderEpoch;
      // A reset must finish parsing after old queued writes before replay can
      // apply its initial geometry. Keep this barrier outside the UART bytes.
      ctx.term.write('\x1bc', function () {
        if (!isCurrent(ctx) || epoch !== ctx.renderEpoch) return;
        ctx.serialCols = null; ctx.serialRows = 24; ctx.serialMode = 'text'; ctx.linuxConsole = false;
        ctx.bootScanTail = ''; ctx.phaseScanTail = '';
        resetProgress(ctx);
        ctx.renderBusy = false; drainRenderQueue(ctx);
      });
      $('d-status').textContent = ' 正在从采集缓冲完整重绘…';
      if (ctx.kind === 'log') {
        var archived = options.session(ctx.sid);
        if (archived && archived.payload) {
          writeTerminalPayload(ctx, archived.payload);
          $('d-status').textContent = archived.status || ' 只读归档已重绘';
        }
        return;
      }
      startStream(ctx);
    }

    function idleSerialPrompt(ctx) {
      if (!isCurrent(ctx) || ctx.sid !== 'serial' || ctx.readonly || ctx.inputSending
          || ctx.internalOutput
          || ctx.inputQueue.length && !ctx.serialStartupPending || (ctx.progress && ctx.progress.active())) return false;
      var b = ctx.term.buffer.active;
      if (b.type === 'alternate') return false;
      var line = b.getLine(b.baseY + b.cursorY);
      return !!line && /^(?:[^\s@]+@[^\s]+[#$]|\[[^\]\r\n]*@[^\]\r\n]+\][#$])\s*$/.test(line.translateToString(true));
    }
    function requestSerialSize(ctx, automatic) {
      if (!idleSerialPrompt(ctx) || ctx.serialSizePending) {
        if (!automatic && isCurrent(ctx)) $('d-status').textContent = ' 请在空闲 Linux shell 提示符处同步尺寸';
        return;
      }
      var dimensions = ctx.fit.proposeDimensions();
      if (!dimensions) return;
      var render = ctx.term._core && ctx.term._core._renderService;
      var cell = render && render.dimensions.css && render.dimensions.css.cell;
      var viewport = ctx.term.element && ctx.term.element.querySelector('.xterm-viewport');
      var ratio = ctx.term.options.fontSize / DEFAULT_TERMINAL_FONT_SIZE;
      var rows = viewport && cell && cell.height ? Math.floor((viewport.clientHeight - 2) * ratio / cell.height) : dimensions.rows;
      var cols = viewport && cell && cell.width ? Math.floor((viewport.clientWidth - 17) * ratio / cell.width) : dimensions.cols;
      rows = Math.max(2, Math.min(200, rows)); cols = Math.max(20, Math.min(500, cols));
      var signature = ctx.off + ':' + cols + ':' + rows;
      if (automatic && signature === ctx.autoSizeAttempt) return;
      ctx.autoSizeAttempt = signature; ctx.serialSizePending = true;
      var sizeGeometryGen = ctx.geometryGen;
      fetch('/api/session-resize', {method: 'POST', headers: {'Content-Type': 'application/json'},
        body: JSON.stringify({key: ctx.key, serial: ctx.serial, sid: 'serial',
          cols: cols, rows: rows, observed_off: ctx.off, automatic: automatic})})
        .then(function (r) { return r.json(); }).then(function (d) {
          if (!isCurrent(ctx)) return;
          if (ctx.geometryGen !== sizeGeometryGen) return;
          if (d.geometry && !ctx.screenManaged) applySerialGeometry(ctx, d.geometry);
          if (ctx.serialStartupPending && (!d.ok || d.skipped)) {
            ctx.serialStartupPending = false; flushInput(ctx);
          }
          if (!d.ok && !automatic) $('d-status').textContent = ' 写入失败：' + (d.error || '');
        }).catch(function (e) {
          if (isCurrent(ctx) && ctx.serialStartupPending) { ctx.serialStartupPending = false; flushInput(ctx); }
          if (!automatic && isCurrent(ctx)) $('d-status').textContent = ' 写入失败：' + e.message;
        }).finally(function () { ctx.serialSizePending = false; });
    }
    function syncSerialSize() { requestSerialSize(view, false); }
    function scheduleSerialSize(ctx) {
      clearTimeout(ctx.serialSizeTimer);
      if (!idleSerialPrompt(ctx)) return;
      ctx.serialSizeTimer = setTimeout(function () { requestSerialSize(ctx, true); }, 400);
    }
    function applySerialGeometry(ctx, geometry) {
      if (ctx.sid !== 'serial' || !geometry || geometry.rows < 2 || geometry.rows > 200
          || geometry.cols < 20 || geometry.cols > 500) return;
      if (ctx.serialMode === 'shell' && ctx.serialRows === geometry.rows && ctx.serialCols === geometry.cols) return;
      ctx.serialRows = geometry.rows; ctx.serialCols = geometry.cols;
      ctx.serialMode = 'shell'; ctx.linuxConsole = true;
      fitTerminal(ctx); syncTerminalLayers(ctx);
    }

    function applyManagedGeometry(ctx, geometry) {
      if (!geometry) return;
      ctx.screenGeometry = geometry;
      fitTerminal(ctx); syncTerminalLayers(ctx);
    }
    function updateTerminalState(ctx, payload, metadataOnly) {
      if (!isCurrent(ctx) || !payload.terminal_state) return;
      var state = payload.terminal_state;
      ctx.internalOutput = !!state.managed && !!state.internal_output;
      if (state.managed) {
        ctx.terminalRevision = state.revision;
        if (!metadataOnly) {
          ctx.screenManaged = true; ctx.screenPhase = state.phase;
          ctx.linuxConsole = state.phase !== 'firmware';
          applyManagedGeometry(ctx, state.geometry);
        }
      }
      ctx.serialConfigured = state.serial_configured;
      if (ctx.serialStartupPending && state.serial_configured && state.serial_ready) {
        ctx.serialStartupPending = false; flushInput(ctx);
      }
      if (typeof payload.terminal_writable === 'boolean' && ctx.sid !== 'serial') {
        if (state.control_revision < (ctx.controllerRevision || 0)) return;
        ctx.controllerRevision = state.control_revision || 0;
        if (ctx.readonly && payload.terminal_writable) ctx.lastSizeRequest = null;
        var controlChanged = ctx.readonly === payload.terminal_writable;
        ctx.readonly = !payload.terminal_writable; ctx.canTakeover = ctx.readonly;
        if (ctx.readonly) {
          ctx.inputQueue = []; clearTimeout(ctx.inputTimer); ctx.inputTimer = 0;
          clearTimeout(ctx.sizeTimer); ctx.sizeTimer = 0;
        }
        ctx.term.options.cursorBlink = !ctx.readonly;
        options.setInputMode(ctx);
        if (controlChanged && options.onControlChange) options.onControlChange(ctx);
      }
      if (state.error) $('d-status').textContent = ' 终端状态不可用：' + state.error;
    }

    function resizeTerm() {
      var ctx = view;
      if (!isCurrent(ctx)) return;
      try { fitTerminal(ctx); syncTerminalLayers(ctx); } catch (e) {}
      if (window.requestAnimationFrame) window.requestAnimationFrame(function () {
        if (!isCurrent(ctx)) return;
        try { fitTerminal(ctx); syncTerminalLayers(ctx); ctx.term.refresh(0, ctx.term.rows - 1); } catch (e) {}
        pushSize(ctx);
      });
      pushSize(ctx);
      scheduleSerialSize(ctx);
      options.scheduleCommandNav(ctx);
    }
    function visibleTerminalRows(ctx, dimensions) {
      var proposed = dimensions && dimensions.rows ? dimensions.rows : ctx.term.rows;
      var element = ctx.term.element;
      if (!element || !element.querySelector) return proposed;
      var viewport = element.querySelector('.xterm-viewport');
      var screen = element.querySelector('.xterm-screen');
      var cellHeight = screen && ctx.term.rows
        ? screen.getBoundingClientRect().height / ctx.term.rows : 0;
      return viewport && viewport.clientHeight && cellHeight > 0
        ? Math.min(proposed, Math.floor(viewport.clientHeight / cellHeight)) : proposed;
    }
    function serialCapacity(ctx, dimensions) {
      var viewport = ctx.term.element && ctx.term.element.querySelector('.xterm-viewport');
      var render = ctx.term._core && ctx.term._core._renderService;
      var cell = render && render.dimensions.css && render.dimensions.css.cell;
      // CharSizeService measures synchronously when fontSize changes. Renderer
      // dimensions can still describe the previous font until the next frame;
      // using those in the fitting loop repeatedly shrinks an already-fit grid.
      var chars = ctx.term._core && ctx.term._core._charSizeService;
      if (chars && chars.width > 0 && chars.height > 0) {
        var dpr = window.devicePixelRatio || 1;
        cell = {width: chars.width + Math.round(ctx.term.options.letterSpacing || 0) / dpr,
          height: Math.floor(Math.ceil(chars.height * dpr) * (ctx.term.options.lineHeight || 1)) / dpr};
      }
      if (viewport && cell && cell.width && cell.height) return {
        cols: Math.floor((viewport.clientWidth - 17) / cell.width),
        rows: Math.floor((viewport.clientHeight - 2) / cell.height)
      };
      return {cols: dimensions && dimensions.cols, rows: visibleTerminalRows(ctx, dimensions)};
    }
    function fitTerminal(ctx) {
      // UART has no PTY window-size negotiation. Linux serial consoles,
      // readline, EDK2 and GRUB normally lay out against 80 columns; fitting
      // xterm to a wide browser makes wrapped input and cursor-left disagree
      // about the visual row. Use 80 columns until explicit shell size sync.
      if (ctx.screenManaged || ctx.sid === 'serial' && ctx.serialMode !== 'text') {
        var required = ctx.screenManaged ? ctx.screenGeometry.rows : ctx.serialRows || 24;
        var cap = !ctx.linuxConsole && required >= 40 && document.body.classList.contains('terminal-max')
          ? 10 : DEFAULT_TERMINAL_FONT_SIZE;
        var requiredCols = ctx.screenManaged ? ctx.screenGeometry.cols : ctx.serialCols || 80;
        var viewport = ctx.term.element && ctx.term.element.querySelector('.xterm-viewport');
        var signature = viewport && viewport.clientWidth && viewport.clientHeight
          ? [viewport.clientWidth, viewport.clientHeight, requiredCols, required, cap,
            ctx.term.options.fontFamily, ctx.term.options.lineHeight, ctx.term.options.letterSpacing,
            window.devicePixelRatio || 1].join(':') : '';
        if (signature && signature === ctx.fixedFitSignature) {
          if (ctx.term.cols !== requiredCols || ctx.term.rows !== required) ctx.term.resize(requiredCols, required);
          return;
        }
        if (ctx.term.options.fontSize !== cap) ctx.term.options.fontSize = cap;
        var dimensions = ctx.fit.proposeDimensions ? ctx.fit.proposeDimensions() : null;
        var capacity = serialCapacity(ctx, dimensions);
        var visibleRows = capacity.rows;
        // Shared UART has one logical grid. Fit the same grid in a smaller
        // viewer by changing only pixels, never terminal rows/columns.
        var fontSize = cap;
        while (dimensions && dimensions.rows && dimensions.cols
            && (visibleRows < required || capacity.cols < requiredCols) && fontSize > 1) {
          var scale = Math.min(visibleRows / required, capacity.cols / requiredCols);
          fontSize = Math.max(1, Math.min(fontSize - .5, Math.floor(fontSize * scale * 2) / 2));
          ctx.term.options.fontSize = fontSize;
          dimensions = ctx.fit.proposeDimensions();
          if (!dimensions) break;
          capacity = serialCapacity(ctx, dimensions);
          visibleRows = capacity.rows;
        }
        var rows = required;
        var cols = requiredCols;
        if (ctx.term.cols !== cols || ctx.term.rows !== rows) ctx.term.resize(cols, rows);
        ctx.fixedFitSignature = signature;
        return;
      }
      ctx.fixedFitSignature = '';
      if (ctx.term.options.fontSize !== DEFAULT_TERMINAL_FONT_SIZE)
        ctx.term.options.fontSize = DEFAULT_TERMINAL_FONT_SIZE;
      // FitAddon calculates width from the host and subtracts a scrollbar even
      // when Chromium uses overlay scrollbars. Measure the actual viewport so
      // the PTY column count matches the pixels xterm can paint.
      var viewport = ctx.term.element && ctx.term.element.querySelector
        ? ctx.term.element.querySelector('.xterm-viewport') : null;
      var renderDimensions = ctx.term._core && ctx.term._core._renderService
        && ctx.term._core._renderService.dimensions;
      var cell = renderDimensions && renderDimensions.css && renderDimensions.css.cell
        && renderDimensions.css.cell.width;
      if (!viewport || !viewport.clientWidth || !cell) {
        var fallback = ctx.fit.proposeDimensions();
        if (ctx.sid === 'serial' && fallback) ctx.term.resize(fallback.cols, fallback.rows);
        else ctx.fit.fit();
        return;
      }
      var proposed = ctx.fit.proposeDimensions();
      var cols = Math.max(2, Math.floor((viewport.clientWidth - (ctx.sid === 'serial' ? 17 : 1)) / cell));
      var rows = Math.max(1, visibleTerminalRows(ctx, proposed));
      if (ctx.term.cols !== cols || ctx.term.rows !== rows) ctx.term.resize(cols, rows);
    }
    function syncTerminalLayers(ctx) {
      if (!ctx || !ctx.term || !ctx.term.element || !ctx.term.element.querySelector) return;
      var viewport = ctx.term.element.querySelector('.xterm-viewport');
      var screen = ctx.term.element.querySelector('.xterm-screen');
      if (!viewport || !screen || !viewport.clientWidth) return;
      if (ctx.sid !== 'serial') {
        // Columns already fit the measured viewport; clip only xterm's spare
        // pixels beyond that width, never a rendered character cell.
        screen.style.width = viewport.clientWidth + 'px';
        screen.style.maxWidth = viewport.clientWidth + 'px';
        screen.style.overflow = 'hidden';
        return;
      }
      // The 80-column serial canvas can be wider than a narrow viewport. Leave
      // an explicit hit area for the scrollbar, including overlay scrollbars.
      var screenWidth = Math.max(0, viewport.clientWidth - 16) + 'px';
      screen.style.width = screenWidth;
      screen.style.maxWidth = screenWidth;
      screen.style.overflow = 'hidden';
    }
    // 把浏览器终端尺寸推给后端,后端 ioctl 到 pty —— 否则远端以为自己是 80x24,
    // 宽度用不满,vi/htop 也按错误列数画。串口那条没法协商(线路上没有 window-change)。
    function pushSize(ctx) {
      if (!isCurrent(ctx) || ctx.sid === 'serial' || ctx.readonly) return;
      clearTimeout(ctx.sizeTimer);
      ctx.sizeTimer = setTimeout(function () {
        if (!isCurrent(ctx) || ctx.readonly) return;
        var dimensions = ctx.fit.proposeDimensions();
        if (ctx.screenManaged) {
          var capacity = serialCapacity(ctx, dimensions);
          var ratio = ctx.term.options.fontSize / DEFAULT_TERMINAL_FONT_SIZE;
          dimensions = {cols: Math.floor(capacity.cols * ratio), rows: Math.floor(capacity.rows * ratio)};
        } else dimensions = {cols: ctx.term.cols, rows: ctx.term.rows};
        var signature = dimensions.cols + ':' + dimensions.rows;
        if (signature === ctx.lastSizeRequest) return;
        ctx.lastSizeRequest = signature;
        fetch('/api/session-resize', { method: 'POST', headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ key: ctx.key, serial: ctx.serial, sid: ctx.sid, cols: dimensions.cols, rows: dimensions.rows })
        }).catch(function () { ctx.lastSizeRequest = null; });
      }, 250);
    }
    window.addEventListener('resize', resizeTerm);
    // Device metadata and tab controls can change height without a window resize.
    // Refit after the terminal host itself changes so its last row stays visible.
    if (window.ResizeObserver) {
      new window.ResizeObserver(resizeTerm).observe($('d-term'));
    }
    // 后台标签页里 rAF 被暂停,xterm 渲染器停摆;切回来要重算尺寸 + 强制重绘,
    // 否则表现为"切走再切回来终端就不渲染了,得刷新"(踩过)
    document.addEventListener('visibilitychange', function () {
      if (document.visibilityState === 'visible') {
        resizeTerm();
        if (term) { try { term.refresh(0, term.rows - 1); } catch (e) {} }
      }
    });

    function writeTerminalPayload(ctx, payload) {
      if (!isCurrent(ctx)) return;
      ctx.renderQueue.push(payload);
      drainRenderQueue(ctx);
    }
    function drainRenderQueue(ctx) {
      if (!isCurrent(ctx) || ctx.renderBusy || !ctx.renderQueue.length) return;
      var payload = ctx.renderQueue.shift(), epoch = ctx.renderEpoch;
      ctx.renderBusy = true;
      renderTerminalPayload(ctx, payload, function () {
        if (!isCurrent(ctx) || epoch !== ctx.renderEpoch) return;
        ctx.renderBusy = false; drainRenderQueue(ctx);
      });
    }
    function renderTerminalPayload(ctx, payload, done) {
      var epoch = ctx.renderEpoch;
      if (!isCurrent(ctx)) return;
      if (payload.terminal_state && payload.terminal_state.managed) {
        updateTerminalState(ctx, payload);
        var snapshot = payload.terminal_snapshot;
        var raw = snapshot ? '\x18\x1bc' + atob(snapshot.data || '') + atob(snapshot.pending || '') : atob(payload.data_b64 || '');
        if (snapshot) {
          options.clearCommandDecorations(ctx);
          // Reset inside the ordered write, not between asynchronous xterm
          // writes. CAN also cancels an unfinished OSC/DCS before replaying RIS.
          ctx.term.clearSelection();
          applyManagedGeometry(ctx, snapshot.geometry);
        }
        var written = function () {
          if (!isCurrent(ctx) || epoch !== ctx.renderEpoch) return;
          ctx.initialRendered = true;
          if (snapshot) scheduleFullRefresh(ctx);
          scheduleSerialSize(ctx); pushSize(ctx);
          if (ctx.sid === 'serial' && ctx.screenPhase === 'text' && !ctx.readonly && !ctx.internalOutput
              && !ctx.inputQueue.length && !ctx.inputSending) {
            var capacity = serialCapacity(ctx, ctx.fit.proposeDimensions());
            var ratio = ctx.term.options.fontSize / DEFAULT_TERMINAL_FONT_SIZE;
            var cols = Math.floor(capacity.cols * ratio), rows = Math.floor(capacity.rows * ratio);
            var size = cols + ':' + rows;
            if (ctx.presentationAttempt !== size) {
              ctx.presentationAttempt = size;
              fetch('/api/session-resize', {method: 'POST', headers: {'Content-Type': 'application/json'},
                body: JSON.stringify({key: ctx.key, serial: ctx.serial, sid: 'serial', cols: cols, rows: rows,
                  observed_off: ctx.off, automatic: true, presentation: true})}).catch(function () {});
            }
          }
          options.scheduleCommandNav(ctx); done();
        };
        if (raw) ctx.term.write(Uint8Array.from(raw, function (c) { return c.charCodeAt(0); }), written);
        else written();
        return;
      }
      // The archive endpoint returns the complete file.  Expand xterm's buffer
      // to the payload's line count before writing so the UI does not silently
      // evict the beginning of a large daily log.
      if (ctx.kind === 'log' && typeof payload.data === 'string') {
        var lines = payload.data.split('\n').length + 10;
        if (lines > ctx.term.options.scrollback) ctx.term.options.scrollback = lines;
      }
      if (payload.terminal_initial_geometry) applySerialGeometry(ctx, payload.terminal_initial_geometry);
      var redraw = false;
      function newestBootCycle(raw) {
        if (ctx.sid !== 'serial' || !raw) return raw;
        // The collector buffer can contain several resets.  Replaying an old
        // EDK2 screen followed by a new boot's plain text preserves highlighted
        // background rows because Boot ROM/U-Boot do not clear a terminal they
        // did not create.  Treat an unmistakable boot banner as a new terminal
        // epoch and show only the newest epoch from this payload onward.
        var prefix = ctx.bootScanTail || '';
        var joined = prefix + raw;
        var pattern = /(?:\x00sys:\s*0x[0-9a-f]+|(?:^|\r?\n)U-Boot(?: SPL)? \d{4}\.\d{2})/ig;
        var match, cut = -1;
        while ((match = pattern.exec(joined))) {
          if (match.index + match[0].length > prefix.length) {
            cut = Math.max(0, match.index - prefix.length);
          }
        }
        ctx.bootScanTail = joined.slice(-32);
        if (cut < 0) return raw;
        options.clearCommandDecorations(ctx);
        try { ctx.term.reset(); ctx.term.clear(); ctx.term.clearSelection(); } catch (e) {}
        ctx.serialRows = 24; ctx.serialCols = null; ctx.serialMode = 'text'; ctx.geometryGen++;
        ctx.phaseScanTail = '';
        ctx.linuxConsole = false;
        ctx.initialRendered = false;
        resetProgress(ctx);
        return raw.slice(cut);
      }
      function prepareSerialGeometry(raw) {
        if (ctx.sid !== 'serial' || !raw) return raw;
        // UEFI commonly paints an 80x50 text console with absolute CUP/HVP
        // coordinates.  Clamping row 50 into a browser-fitted 40-row terminal
        // makes later erases overwrite the whole visible menu.  A full clear
        // starts a new logical screen: GRUB/Linux can therefore leave EDK2's
        // 50-row mode, while another row-50 CUP later in the same frame restores
        // it before xterm parses the payload. Linux boot output ends firmware
        // mode even if firmware never sent a final clear-screen sequence.
        var prefix = ctx.phaseScanTail || '';
        var joined = prefix + raw;
        var pattern = /\x1b\[(?:([0-9]{1,3})(?:;[0-9]{0,3})?[Hf]|2J)|(?:^|\r?\n)(?:\[[^\r\n]{1,40}\]\s*)?Linux version [0-9]|(?:^|\r?\n)\[\s*[0-9]+\.[0-9]{6}\] /g;
        var match, rows = ctx.serialRows || 24, oldMode = ctx.serialMode, oldCols = ctx.serialCols, kernelCut = -1;
        while ((match = pattern.exec(joined))) {
          if (match.index + match[0].length <= prefix.length) continue;
          var kernelBanner = /Linux version [0-9]/.test(match[0]);
          var kernelClock = /\[\s*[0-9]+\.[0-9]{6}\] /.test(match[0]);
          var kernelReset = kernelClock && (!ctx.linuxConsole || payload.terminal_initial_geometry && payload.terminal_geometry === null && kernelCut < 0);
          if (kernelBanner || kernelReset) {
            if (kernelReset || !ctx.linuxConsole || ctx.serialMode === 'firmware') kernelCut = match.index;
            ctx.linuxConsole = true; ctx.geometryGen++;
            ctx.serialCols = null; ctx.serialMode = 'text'; rows = 24;
            continue;
          }
          if (kernelClock) continue;
          if (!match[1]) {
            if (!ctx.serialCols) rows = 24;
            if (!ctx.linuxConsole) ctx.serialMode = 'firmware';
            try { ctx.term.clearSelection(); } catch (e) {}
            continue;
          }
          var row = Number(match[1] || 1);
          if (!ctx.linuxConsole && row >= 1 && row <= 200) {
            ctx.serialMode = 'firmware'; rows = Math.max(rows, row);
          }
        }
        ctx.phaseScanTail = joined.slice(-128);
        if (rows !== ctx.serialRows || oldMode !== ctx.serialMode || oldCols !== ctx.serialCols) {
          ctx.serialRows = rows;
          fitTerminal(ctx);
          syncTerminalLayers(ctx);
        }
        if (kernelCut >= 0) {
          resetProgress(ctx); options.clearCommandDecorations(ctx);
          // RIS clears attributes, origin/scroll modes, saved cursor and old
          // firmware cells in parse order, including previously queued writes.
          return '\x1bc' + joined.slice(kernelCut).replace(/^[\r\n]+/, '');
        }
        return raw;
      }
      function written() {
        if (!isCurrent(ctx) || epoch !== ctx.renderEpoch) return;
        ctx.initialRendered = true;
        if (payload.terminal_geometry && ctx.serialMode !== 'firmware') applySerialGeometry(ctx, payload.terminal_geometry);
        scheduleSerialSize(ctx);
        if (ctx.archiveSearchQuery) {
          $('terminal-search').value = ctx.archiveSearchQuery;
          ctx.archiveSearchQuery = ''; options.searchTerminal(1);
        }
        if (redraw || ctx.sid === 'serial' && ctx.serialMode === 'text') scheduleFullRefresh(ctx);
        options.scheduleCommandNav(ctx);
        done();
      }
      if (typeof payload.data_b64 === 'string') {
        var raw = atob(payload.data_b64);
        if (ctx.sid === 'serial' && ctx.lastRenderedOff != null && payload.off - raw.length !== ctx.lastRenderedOff) resetProgress(ctx);
        ctx.lastRenderedOff = payload.off;
        raw = newestBootCycle(raw);
        raw = prepareSerialGeometry(raw);
        if (ctx.progress) raw = ctx.progress.rewrite(raw);
        // Firmware menus paint the screen with cursor positioning and erases.
        // xterm normally tracks dirty rows, but a large sequence split across
        // HTTP reads can leave canvas layers visually stale until the next input.
        redraw = /\x1b(?:\[[0-9;?]*[ABCDEFGHJKSTfhl]|[78])/.test(raw);
        if (raw.length) {
          // Initial geometry was applied outside the ordered byte stream above.
          // A CSI prefix here would interrupt split OSC/DCS and UTF-8 characters.
          ctx.term.write(Uint8Array.from(raw, function (c) { return c.charCodeAt(0); }),
            written);
        } else written();
      } else if (payload.data) {
        var text = newestBootCycle(payload.data);
        text = prepareSerialGeometry(text);
        if (ctx.progress) text = ctx.progress.rewrite(text);
        redraw = /\x1b(?:\[[0-9;?]*[ABCDEFGHJKSTfhl]|[78])/.test(text);
        ctx.term.write(text, written);
      } else written();
    }

    function scheduleFullRefresh(ctx) {
      if (!isCurrent(ctx) || ctx.refreshFrame) return;
      var refresh = function () {
        ctx.refreshFrame = 0;
        if (!isCurrent(ctx)) return;
        try {
          if (ctx.sid === 'serial') { fitTerminal(ctx); syncTerminalLayers(ctx); }
          ctx.term.refresh(0, ctx.term.rows - 1);
        } catch (e) {}
      };
      if (window.requestAnimationFrame) ctx.refreshFrame = window.requestAnimationFrame(refresh);
      else refresh();
    }

    function startStream(ctx) {
      if (!isCurrent(ctx)) return;
      if (typeof window.EventSource !== 'function') { loop(ctx); return; }
      var url = '/api/session-events?key=' + encodeURIComponent(ctx.key)
        + '&serial=' + encodeURIComponent(ctx.serial || '')
        + '&sid=' + encodeURIComponent(ctx.sid) + '&off=' + ctx.off
        + '&screen=1&terminal_rev=' + (ctx.terminalRevision || 0)
        + '&client_id=' + encodeURIComponent(SerialdUI.clientId);
      var stream = new window.EventSource(url);
      ctx.stream = stream;
      stream.onmessage = function (event) {
        if (!isCurrent(ctx) || ctx.stream !== stream) return;
        var d;
        try { d = JSON.parse(event.data); } catch (e) { stream.onerror(); return; }
        if (!d || d.sid !== ctx.sid || d.key !== ctx.key || typeof d.off !== 'number') {
          stream.onerror(); return;
        }
        if (d.off < ctx.off) return;
        if (ctx.sid === 'serial' && Object.prototype.hasOwnProperty.call(d, 'input_owner')
            && options.updateInputOwner) options.updateInputOwner(ctx, d.input_owner);
        updateTerminalState(ctx, d, true);
        if (d.off === ctx.off && !d.data_b64 && !d.terminal_snapshot && d.alive !== false) return;
        if (d.off === ctx.off && ctx.off > 0 && !d.terminal_snapshot && d.alive !== false) return;
        ctx.off = d.off;
        $('d-dev').textContent = d.dev || d.ip || '';
        writeTerminalPayload(ctx, d);
        if (d.alive === false) {
          stream.close(); ctx.stream = null;
          ctx.loopTimer = setTimeout(function () { loop(ctx); }, 500);
        }
      };
      stream.onerror = function () {
        if (ctx.stream !== stream) return;
        stream.close(); ctx.stream = null;
        if (isCurrent(ctx)) loop(ctx); // Old services and transient SSE failures keep working.
      };
    }

    function loop(ctx) {
      if (!isCurrent(ctx)) return;
      var readSeq = ++ctx.readSeq;
      var nextDelay = 10;
      ctx.ctrl = new AbortController();
      fetch('/api/session?key=' + encodeURIComponent(ctx.key) + '&serial=' + encodeURIComponent(ctx.serial || '') + '&sid=' + encodeURIComponent(ctx.sid)
            + '&off=' + ctx.off + '&screen=1&terminal_rev=' + (ctx.terminalRevision || 0)
            + '&client_id=' + encodeURIComponent(SerialdUI.clientId), { cache: 'no-store', signal: ctx.ctrl.signal })
        .then(function (r) { return r.json(); })
        .then(function (d) {
          if (!isCurrent(ctx) || readSeq !== ctx.readSeq) return; // 切换/重绘后的旧响应,丢弃
          if (!d || d.error) throw new Error(d && d.error || 'error');
          if ((d.key && d.key !== ctx.key) || (d.sid && d.sid !== ctx.sid)) {
            throw new Error('会话响应与请求不匹配');
          }
          ctx.off = d.off;
          updateTerminalState(ctx, d, true);
          nextDelay = d.alive === false ? 500 : 10;
          $('d-dev').textContent = d.dev || d.ip || '';
          // 原始字节直接交给 xterm —— 光标定位、颜色、备用屏幕缓冲都由它处理,
          // vim/htop 这类全屏程序才能正确重画(剥 ANSI 再追加会糊成一团)
          // JSON 每块先转字符串会截断跨块 UTF-8（中文尤其明显）。传原始字节，
          // 由此会话自己的 xterm 解码器保留半个字符；切会话时解码器也一起销毁。
          writeTerminalPayload(ctx, d);   // data 字段兼容仍在运行的旧服务
        })
        .catch(function (e) {
          if (!isCurrent(ctx) || readSeq !== ctx.readSeq || (e && e.name === 'AbortError')) return;
          $('d-status').textContent = ' 读取失败：' + e.message;
        })
        .finally(function () {
          if (!isCurrent(ctx) || readSeq !== ctx.readSeq) return;
          // 定时器本身也必须绑定视图，否则旧定时器会多开一条新会话轮询。
          // /api/session is already a long poll.  Start the next read promptly
          // after output so terminal echo is not held behind an extra 300 ms.
          ctx.loopTimer = setTimeout(function () { loop(ctx); }, nextDelay);
        });
    }

    function flushInput(ctx) {
      if (!isCurrent(ctx) || ctx.serialStartupPending || ctx.inputSending || ctx.inputTimer || !ctx.inputQueue.length) return;
      var item = ctx.inputQueue.shift();
      ctx.inputSending = true;
      fetch('/api/session-send', { method: 'POST', headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ key: ctx.key, serial: ctx.serial, sid: ctx.sid, data: item.data }) })
        .then(function (r) { return r.json(); })
        .then(function (d) {
          if (!isCurrent(ctx)) return;
          if (!d.ok) {
            $('d-status').textContent = ' 写入失败：' + (d.error || '');
            if (d.code === 'session-controlled') {
              ctx.readonly = true; ctx.canTakeover = true; ctx.inputQueue = [];
              options.setInputMode(ctx);
            }
          }
          else if (/[\r\n]/.test(item.data)) options.loadCommands();
        })
        .catch(function (e) {
          if (isCurrent(ctx)) $('d-status').textContent = ' 写入失败：' + e.message;
        }).finally(function () {
          ctx.inputSending = false;
          if (!isCurrent(ctx)) return;
          if (item.slow && ctx.inputQueue.length) {
            // EFI Serial I/O polling in GRUB can lose a bulk write.  Spacing is
            // opt-in and affects only pasted serial bytes, never normal typing.
            ctx.inputTimer = setTimeout(function () {
              ctx.inputTimer = 0;
              flushInput(ctx);
            }, 50);
          } else flushInput(ctx);
        });
    }

    function send(text, ctx, slow) {
      ctx = ctx || view;
      if (!isCurrent(ctx)) return;
      if (ctx.readonly) {
        $('d-status').textContent = ctx.kind === 'log' ? ' 当前是只读归档日志' : ' 当前会话由另一客户端控制，可介入后输入';
        return;
      }
      if (ctx.screenManaged && ctx.sid === 'serial' && !ctx.serialConfigured && idleSerialPrompt(ctx)) {
        ctx.serialStartupPending = true;
        requestSerialSize(ctx, false);
      }
      clearTimeout(ctx.serialSizeTimer);
      // Preserve order.  Ordinary keystrokes coalesce during a network round
      // trip; firmware paste deliberately stays one character per write.
      var last = ctx.inputQueue[ctx.inputQueue.length - 1];
      if (!slow && last && !last.slow) last.data += text;
      else ctx.inputQueue.push({ data: text, slow: !!slow });
      flushInput(ctx);
    }

    var controller = {
      isCurrent: isCurrent, create: createView, dispose: disposeView,
      resize: resizeTerm, redraw: redrawTerminal, syncSerialSize: syncSerialSize,
      write: writeTerminalPayload, start: startStream, send: send, updateState: updateTerminalState
    };
    Object.defineProperty(controller, 'current', { get: function () { return view; } });
    return controller;
  }
  global.SerialdTerminalView = { create: create };
})(window);
